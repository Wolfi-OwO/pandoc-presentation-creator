#!/bin/bash
set -e

# ==============================================================================
# Interactive Initialization for Presentation Project
# ==============================================================================

GREEN='\033[0;32m'
BLUE='\033[0;34m'
NC='\033[0m'

echo -e "${BLUE}--- Pandoc Presentation Project Initialization ---${NC}"

# 1. Configuration Prompt
echo ""
echo "Please configure your project metadata."
read -p "Project Title: " TITLE
read -p "Author Name: " AUTHOR

echo ""
echo "Select a Beamer Theme:"
echo "1) Madrid (Standard)"
echo "2) Metropolis (Modern)"
read -p "Enter choice [1]: " THEME_OPT

case $THEME_OPT in
  2) THEME="Metropolis" ;;
  *) THEME="Madrid" ;;
esac

# 2. Create Project Structure
mkdir -p config
mkdir -p presentation
mkdir -p pandoc/defaults
mkdir -p pandoc/templates
mkdir -p output
# Add default READMEs for structure
echo "Place custom Pandoc templates (.latex, .html) here." > pandoc/templates/README.md
echo "Place custom Defaults files (.yaml) here." > pandoc/defaults/README.md
# 3. Write Configuration File
cat <<YAML > config/settings.yaml
# Presentation Configuration
title: "$TITLE"
author: "$AUTHOR"
date: "$(date +%Y-%m-%d)"
theme: "$THEME"
output_dir: "output"
input: "presentation/Example.md"
docker_image: "ghcr.io/woofistudios/pandoc-beamer:latest"
YAML
echo -e "${GREEN}Configuration saved to config/settings.yaml${NC}"

# 4. Create Example Presentation
cat <<MD > presentation/Example.md
---
title: "$TITLE"
subtitle: "Created with Pandoc Presentation Creator"
author: "$AUTHOR"
date: \today
theme: "$THEME"
---

# Introduction

## Welcome

This is an example presentation generated by the initialization script.

-   **Theme**: $THEME
-   **Author**: $AUTHOR

## Features

-   Markdown-based slides
-   Dockerized build process
-   Professional PDF output

# Content

## Code Block Example

\`\`\`python
def hello_world():
    print("Hello from Pandoc!")
\`\`\`
MD
echo -e "${GREEN}Example presentation created at presentation/Example.md${NC}"

# 5. Create Help File
cat <<HELP > HELP.md
# Project Help

## How to Build

Run the build script to generate your PDF slides:

    ./scripts/build.sh

The output PDF will be placed in the `output/` directory.

## Customization

- **Content**: Edit `presentation/Example.md` or create new Markdown files.
- **Settings**: Modify `config/settings.yaml` to change themes, titles, or input files.

## Docker

The build uses the image defined in `docker_image` in settings.yaml.

HELP
echo -e "${GREEN}HELP.md created${NC}"

# 6. Docker Setup
echo ""
echo "Checking for Docker..."
if command -v docker &> /dev/null; then
    echo -e "${BLUE}Docker found. Building local image from registry Dockerfile...${NC}"
    # Building with the registry tag so local runs use it immediately
    docker build -t ghcr.io/woofistudios/pandoc-beamer:latest -f docker/Dockerfile.beamer .
    echo -e "${GREEN}Docker Image built successfully.${NC}"
else
    echo "Docker executable not found. Please ensure Pandoc and TeXLive are installed locally."
fi

echo ""
echo "Setup Complete."
echo "Read HELP.md for more information."
