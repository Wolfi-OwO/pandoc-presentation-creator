#!/bin/bash
set -e

# ==============================================================================
# Universal Presentation Engine - Bootstrap Initialization
# ==============================================================================
# This script downloads all necessary files and sets up a complete project

GREEN='\033[0;32m'
BLUE='\033[0;34m'
RED='\033[0;31m'
NC='\033[0m'

REPO_URL="https://gitlab.com/woofi4/public/pandoc-presentation-creator/-/raw/main"
PROJECT_DIR="$(pwd)"

echo -e "${BLUE}--- Pandoc Presentation Project Bootstrap ---${NC}"

# Step 1: Configuration
echo ""
echo "Please configure your project metadata."
read -p "Project Title: " TITLE
read -p "Author Name: " AUTHOR

echo ""
echo "Select a Beamer Theme:"
echo "1) Madrid (Standard)"
echo "2) Metropolis (Modern)"
read -p "Enter choice [1]: " THEME_OPT

case $THEME_OPT in
  2) THEME="Metropolis" ;;
  *) THEME="Madrid" ;;
esac

# Step 2: Create Only User-Facing Directory Structure
echo ""
echo "Creating project directories..."
mkdir -p output
mkdir -p config
mkdir -p slides

echo -e "${GREEN}Directory structure created${NC}"

# Step 3: No need to download - using Docker image from registry
echo ""
echo "Using Docker image from registry: ${REPO_URL%%-/raw/*}/container_registry"

# Step 4: Create Project Settings
echo ""
echo "Creating project configuration..."
cat > config/settings.yaml <<YAML
# Presentation Configuration
title: "$TITLE"
author: "$AUTHOR"
date: "$(date +%Y-%m-%d)"
theme: "$THEME"
output_dir: "output"
input: "slides/Example.md"
docker_image: "registry.gitlab.com/woofi4/public/pandoc-presentation-creator:latest"
YAML

echo -e "${GREEN}Configuration saved to config/settings.yaml${NC}"

# Step 5: Create Example Presentation
echo ""
echo "Creating example presentation..."
cat > slides/Example.md <<'MD'
---
title: "TITLE_PLACEHOLDER"
subtitle: "Created with Pandoc Presentation Creator"
author: "AUTHOR_PLACEHOLDER"
date: \today
theme: "THEME_PLACEHOLDER"
---

# Introduction

## Welcome

This is an example presentation generated by the initialization script.

- **Theme**: THEME_PLACEHOLDER
- **Author**: AUTHOR_PLACEHOLDER

## Features

- Markdown-based slides
- Dockerized build process
- Professional PDF output

# Content

## Code Block Example

```python
def hello_world():
    print("Hello from Pandoc!")
```

## Conclusion

- Easy to customize
- Ready to build
- Production ready
MD

# Replace placeholders in example
sed -i "s/TITLE_PLACEHOLDER/$TITLE/g" slides/Example.md
sed -i "s/AUTHOR_PLACEHOLDER/$AUTHOR/g" slides/Example.md
sed -i "s/THEME_PLACEHOLDER/$THEME/g" slides/Example.md

echo -e "${GREEN}Example presentation created at slides/Example.md${NC}"

# Step 6: Create Minimal Documentation
echo ""
echo "Creating documentation..."
cat > HELP.md <<'HELP'
# Quick Start

Build your presentation using Docker:

    docker run --rm -v $(pwd):/data registry.gitlab.com/woofi4/public/pandoc-presentation-creator:latest python3 scripts/build.py --input slides/Example.md

Output PDF will be in the `output/` directory.

## Editing

1. Edit `slides/Example.md` with your content
2. Update `config/settings.yaml` if needed
3. Run the docker command above to build

HELP

cat > README.md <<'README'
# Presentation Project

Generated by Universal Presentation Engine

## Getting Started

1. Edit `slides/Example.md` with your content
2. Run Docker build command (see HELP.md)
3. Output will be in `output/`

HELP

echo -e "${GREEN}Documentation created${NC}"

# Step 7: Create .gitignore
cat > .gitignore <<'GITIGNORE'
output/
*.pdf
*.html
*.pptx
.DS_Store
GITIGNORE

# Step 8: Pull Docker Image from Registry
echo ""
echo "Configuring Docker image from registry..."
DOCKER_IMAGE="registry.gitlab.com/woofi4/public/pandoc-presentation-creator:latest"

if command -v docker &> /dev/null; then
    echo -e "${BLUE}Pulling Docker image from registry...${NC}"
    docker pull "$DOCKER_IMAGE" || echo "Note: Could not pull image. Ensure you have internet access."
    echo -e "${GREEN}Docker image ready${NC}"
    echo ""
    echo "To build your presentation, run:"
    echo "docker run --rm -v \$(pwd):/data $DOCKER_IMAGE python3 scripts/build.py --input slides/Example.md"
else
    echo "Docker not found. Please install Docker to use this project."
fi

# Step 9: Initialize git (optional)
echo ""
if [ ! -d .git ]; then
    read -p "Initialize git repository? [Y/n]: " INIT_GIT
    if [ "$INIT_GIT" != "n" ]; then
        git init
        git add .
        git commit -m "Initial commit: Presentation project setup"
        echo -e "${GREEN}Git repository initialized${NC}"
    fi
fi

echo ""
echo -e "${GREEN}Setup Complete!${NC}"
echo ""
echo "Your project structure:"
echo "  config/      - Configuration files"
echo "  slides/      - Your markdown presentations"
echo "  output/      - Generated PDFs and outputs"
echo ""
echo "Next steps:"
echo "1. Edit slides/Example.md"
echo "2. See HELP.md for build instructions"
echo "3. Docker image includes: templates, filters, build scripts, themes"
